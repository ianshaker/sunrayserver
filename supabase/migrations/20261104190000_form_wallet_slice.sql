-- ============================================================================
-- Срез кошелька мастера — одной операцией в базе (разбор CRM/28, пункт 6, «запись денег одной операцией»).
--
-- Было (sunray-crm-oasis …/wallet/services/sliceService.ts, сформироватьСрезБезПроверки): браузер пишет срез
-- десятком запросов подряд — выравнивание, балансировка, маркер, строки по одной, удаление из кошелька, долги.
-- Обрыв или двойное нажатие оставляли строки и в срезе, и в кошельке (12 пар дублей в walletfinal_all,
-- лишние 113 447 ₽); два среза одного мастера разом не блокировались; дата среза бралась по UTC
-- (38 из 2 317 срезов — на день раньше); стёртые старые долги нигде не оставляли следа.
--
-- Стало: form_wallet_slice(мастер, выравнивание, «в долг», что видело окно) делает то же самое в одной
-- транзакции. Логика Глеба та же, правило за правилом:
--   • к срезу — все строки «К срезу», кроме долговых (любой статус); долговые — все строки мастера
--     «ДОЛЖЕН МАСТЕР» / «ДОЛЖНА КОМПАНИЯ»;
--   • баланс считается как рассчитатьБаланс (balanceService.ts) — функция wallet_balance_part ниже;
--   • выравнивание (если есть) — строка «Выравнивание баланса», подтверждена, уходит в срез;
--   • без «в долг» и с ненулевым остатком — строка «Балансировка среза <номер>» на минус остаток;
--   • маркер «Срез», затем строки, выравнивание, балансировка — в walletfinal_all с номером и датой среза;
--   • строки к срезу и все старые долги удаляются из кошелька;
--   • «в долг» — новая строка долга на весь прежний баланс, «неподтверждено», «К срезу».
-- Добавлено (без смены того, что видит Глеб):
--   • всё или ничего: сбой на любом шаге откатывает весь срез;
--   • замок на мастера: второй срез того же мастера ждёт первый и видит уже пустой кошелёк;
--   • метки «договор изменён» проверяются здесь же, под замком (как подЗащитойМеток в CRM);
--   • p_seen — строки, которые видело окно; кошелёк изменился, пока окно было открыто, — отказ;
--   • дата и время среза — по Москве;
--   • журнал wallet_slice_log: кто, когда, баланс до, какие строки ушли, какие старые долги стёрты.
-- Находка, оставлена как есть (логика Глеба): окно считает «Выплату по …» только наличными
-- (рассчитатьБалансКСрезу), а срез — любую (рассчитатьБаланс); разницу закрывает строка балансировки.
-- ============================================================================

begin;
set local lock_timeout = '5s';

-- 1. Вклад строки в баланс кошелька — ровно рассчитатьБаланс из balanceService.ts
create or replace function public.wallet_balance_part(p_event_type text, p_payment_type text, p_amount numeric, p_status text)
 returns numeric
 language sql
 immutable
 set search_path to 'public'
as $function$
  select case
    when p_status is distinct from 'подтверждено' or p_amount is null then 0
    when p_event_type = 'ДОЛЖЕН МАСТЕР' and p_amount > 0 then p_amount
    when p_event_type = 'ДОЛЖНА КОМПАНИЯ' and p_amount > 0 then -p_amount
    when p_event_type in ('Аванс', 'Остаток') and p_payment_type = 'Наличные' and p_amount > 0 then p_amount
    when p_event_type = 'Долг по рекламации' and p_amount > 0 then p_amount
    when p_event_type in ('Выплата по замеру', 'Выплата по монтажу', 'Выплата по бензину') and p_amount < 0 then p_amount
    when p_event_type = 'Выравнивание баланса' then p_amount
    else 0
  end
$function$;

-- 2. Номер проводки, которого ещё нет ни в кошельках, ни в срезах (формат TR-ГГММДД-XXXX, как generate_transaction_number)
create or replace function public.wallet_new_transaction_number()
 returns text
 language plpgsql
 set search_path to 'public'
as $function$
declare
  v_cand text;
begin
  for i in 1..10 loop
    v_cand := public.generate_transaction_number();
    if not exists (select 1 from public.wallet_all w where w.transaction_number = v_cand)
       and not exists (select 1 from public.walletfinal_all f where f.transaction_number = v_cand) then
      return v_cand;
    end if;
  end loop;
  raise exception 'Не удалось выдать номер проводки: 10 совпадений подряд';
end;
$function$;

-- 3. Журнал срезов: след каждого среза, в том числе стёртых старых долгов
create table if not exists public.wallet_slice_log (
  id bigint generated by default as identity primary key,
  master text not null references public.masters(key),
  slice_number text not null unique,
  slice_date date not null,
  mode text not null check (mode in ('выравнивание', 'в долг')),
  balance_before numeric not null,
  moved jsonb not null default '[]'::jsonb,
  adjustment jsonb,
  balancing_amount numeric,
  removed_debts jsonb not null default '[]'::jsonb,
  new_debt jsonb,
  seen jsonb,
  created_by uuid default auth.uid(),
  created_by_name text,
  created_at timestamptz not null default now()
);
create index if not exists wallet_slice_log_master_created_idx on public.wallet_slice_log (master, created_at desc);
alter table public.wallet_slice_log enable row level security;
drop policy if exists wallet_slice_log_read on public.wallet_slice_log;
create policy wallet_slice_log_read on public.wallet_slice_log for select to authenticated using (true);
drop policy if exists wallet_slice_log_add on public.wallet_slice_log;
create policy wallet_slice_log_add on public.wallet_slice_log for insert to authenticated with check (created_by = auth.uid());
revoke all on public.wallet_slice_log from anon, public, authenticated;
grant select, insert on public.wallet_slice_log to authenticated;
grant all on public.wallet_slice_log to service_role;

-- 4. Сам срез
create or replace function public.form_wallet_slice(
  p_master text,
  p_adjustment jsonb default null,
  p_debt jsonb default null,
  p_seen jsonb default null
)
 returns jsonb
 language plpgsql
 set search_path to 'public'
as $function$
declare
  c_debt_types constant text[] := array['ДОЛЖЕН МАСТЕР', 'ДОЛЖНА КОМПАНИЯ'];
  v_uid uuid := auth.uid();
  v_name text;
  v_now timestamp := date_trunc('second', clock_timestamp() at time zone 'Europe/Moscow');
  v_date date := v_now::date;
  v_time time := v_now::time;
  v_adj jsonb := case when jsonb_typeof(p_adjustment) = 'object' then p_adjustment end;
  v_debt jsonb := case when jsonb_typeof(p_debt) = 'object' then p_debt end;
  v_adj_amount numeric;
  v_adj_payment text;
  v_adj_event text;
  v_adj_row jsonb;
  v_debt_comment text;
  v_slice text;
  v_cand text;
  v_block jsonb;
  v_diff integer;
  v_moved jsonb;
  v_regular_n integer;
  v_removed_debts jsonb;
  v_debts_n integer;
  v_initial numeric;
  v_final numeric;
  v_bal_amount numeric;
  v_bal_row jsonb;
  v_new_debt jsonb;
  v_rows integer;
begin
  -- Кто и чей кошелёк
  if v_uid is null then
    raise exception 'Войдите в CRM, чтобы сформировать срез';
  end if;
  select p.full_name into v_name from public.profiles p where p.id = v_uid;
  if p_master is null or not exists (select 1 from public.masters m where m.key = p_master) then
    raise exception 'Срез: мастер «%» не из списка кошельков', coalesce(p_master, '');
  end if;

  -- Что пришло из окна: выравнивание и «в долг» — объект или null, строки окна — обязательный список
  if p_adjustment is not null and jsonb_typeof(p_adjustment) not in ('object', 'null') then
    raise exception 'Срез: выравнивание должно идти объектом';
  end if;
  if p_debt is not null and jsonb_typeof(p_debt) not in ('object', 'null') then
    raise exception 'Срез: «Учесть в долг» должно идти объектом';
  end if;
  if v_adj is not null and v_debt is not null then
    raise exception 'Срез: либо выравнивание, либо «Учесть в долг» — не оба сразу';
  end if;
  if v_adj is not null then
    if jsonb_typeof(v_adj -> 'amount') is distinct from 'number' or (v_adj ->> 'amount')::numeric = 0 then
      raise exception 'Срез: сумма выравнивания должна быть числом, не нулём';
    end if;
    v_adj_amount := (v_adj ->> 'amount')::numeric;
    v_adj_payment := nullif(btrim(v_adj ->> 'payment_type'), '');
    if v_adj_payment is null then
      raise exception 'Срез: не указан способ выравнивания';
    end if;
    v_adj_event := coalesce(nullif(btrim(v_adj ->> 'event'), ''), 'Выравнивание при формировании среза');
  end if;
  if v_debt is not null then
    v_debt_comment := coalesce(nullif(btrim(v_debt ->> 'comment'), ''), 'Отложенная выплата по срезу');
  end if;
  if jsonb_typeof(p_seen) is distinct from 'array' then
    raise exception 'Срез: нет списка строк, которые видело окно';
  end if;

  -- Замок на мастера: второй срез того же мастера ждёт, пока закончится первый (не дольше 5 с на замок)
  perform set_config('lock_timeout', '5s', true);
  perform pg_advisory_xact_lock(hashtextextended('wallet_slice:' || p_master, 0));
  perform 1 from public.wallet_all w
   where w.master = p_master and (w.slice_status = 'to_slice' or w.event_type = any (c_debt_types))
   order by w.id
   for update;

  -- Метки «договор изменён» держат срез (как подЗащитойМеток в CRM)
  select jsonb_agg(jsonb_build_object('id', w.id, 'transaction_number', w.transaction_number, 'event_type', w.event_type,
                                      'amount', w.amount, 'dogovor_number', h.dogovor_number, 'reason', h.reason) order by w.id)
    into v_block
    from public.wallet_all w
    join public.wallet_holds h
      on h.master = w.master and h.released_at is null
     and upper(btrim(h.transaction_number)) = upper(btrim(w.transaction_number))
   where w.master = p_master and w.slice_status = 'to_slice';
  if v_block is not null then
    raise exception 'Срез не сформирован: договор по строке изменён — вытащите её из «К срезу»'
      using detail = v_block::text, hint = 'СРЕЗ_ЗАБЛОКИРОВАН';
  end if;

  -- Окно видело ровно эти строки (номер, сумма, статус, вид, способ)? Иначе кошелёк изменился, пока окно было открыто
  begin
    with seen as (
      select upper(btrim(e ->> 'n')) n, (e ->> 'a')::numeric a, e ->> 's' s, e ->> 'e' ev, e ->> 'p' pt
        from jsonb_array_elements(p_seen) e
    ), cur as (
      select upper(btrim(w.transaction_number)) n, w.amount a, w.status s, w.event_type ev, w.payment_type pt
        from public.wallet_all w
       where w.master = p_master and (w.slice_status = 'to_slice' or w.event_type = any (c_debt_types))
    )
    select count(*) into v_diff from ((select * from seen except select * from cur) union all (select * from cur except select * from seen)) d;
    if v_diff > 0 then
      raise exception 'Кошелёк изменился, пока было открыто окно среза: закройте окно и откройте срез заново'
        using hint = 'КОШЕЛЁК_ИЗМЕНИЛСЯ';
    end if;
  end;

  -- Строки к срезу (без долговых) и все долговые строки мастера
  select coalesce(jsonb_agg(to_jsonb(w) order by w.date, w.created_at, w.id), '[]'::jsonb), count(*)
    into v_moved, v_regular_n
    from public.wallet_all w
   where w.master = p_master and w.slice_status = 'to_slice' and w.event_type <> all (c_debt_types);
  select coalesce(jsonb_agg(to_jsonb(w) order by w.id), '[]'::jsonb), count(*)
    into v_removed_debts, v_debts_n
    from public.wallet_all w
   where w.master = p_master and w.event_type = any (c_debt_types);

  -- Баланс до любых изменений: строки к срезу + все долги
  select coalesce(sum(public.wallet_balance_part(w.event_type, w.payment_type, w.amount, w.status)), 0)
    into v_initial
    from public.wallet_all w
   where w.master = p_master
     and ((w.slice_status = 'to_slice' and w.event_type <> all (c_debt_types)) or w.event_type = any (c_debt_types));

  if v_regular_n = 0 and v_debt is null then
    return jsonb_build_object('ok', false, 'reason', 'Нет строк к срезу');
  end if;

  -- Номер среза: SLICE-ГГГГММДД-ЧЧММСС-XXXX по Москве
  for i in 1..10 loop
    v_cand := 'SLICE-' || to_char(v_now, 'YYYYMMDD-HH24MISS') || '-'
              || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 4));
    if not exists (select 1 from public.walletfinal_all f where f.slice_number = v_cand or f.transaction_number = v_cand) then
      v_slice := v_cand;
      exit;
    end if;
  end loop;
  if v_slice is null then
    raise exception 'Срез: не удалось выдать номер среза';
  end if;

  -- Остаток строк к срезу вместе с выравниванием; без «в долг» его закрывает балансировка
  select coalesce(sum(public.wallet_balance_part(w.event_type, w.payment_type, w.amount, w.status)), 0)
    into v_final
    from public.wallet_all w
   where w.master = p_master and w.slice_status = 'to_slice' and w.event_type <> all (c_debt_types);
  if v_adj is not null then
    v_final := v_final + public.wallet_balance_part('Выравнивание баланса', v_adj_payment, v_adj_amount, 'подтверждено');
  end if;
  if v_final <> 0 and v_debt is null then
    v_bal_amount := -v_final;
  end if;

  -- В срез: маркер, строки по порядку, выравнивание, балансировка (created_at растёт по порядку)
  insert into public.walletfinal_all (master, transaction_number, date, slice_date, time, event_type, event, payment_type,
                                      amount, status, slice_number, created_at, updated_at)
  values (p_master, v_slice, v_date, v_date, v_time, 'Срез', 'Срез кошелька от ' || to_char(v_date, 'DD.MM.YYYY'),
          'Системная операция', 0, 'подтверждено', v_slice, clock_timestamp(), clock_timestamp());

  insert into public.walletfinal_all (master, transaction_number, date, event_type, event, appeal_id, payment_type, amount,
                                      receipt_photo, status, time, slice_date, slice_number, created_at, updated_at)
  select p_master, w.transaction_number, w.date, w.event_type, w.event, w.appeal_id, w.payment_type, w.amount,
         w.receipt_photo, w.status, w.time, v_date, v_slice, clock_timestamp(), clock_timestamp()
    from public.wallet_all w
   where w.master = p_master and w.slice_status = 'to_slice' and w.event_type <> all (c_debt_types)
   order by w.date, w.created_at, w.id;
  get diagnostics v_rows = row_count;
  if v_rows <> v_regular_n then
    raise exception 'Срез: в срез ушло % строк, ожидали %', v_rows, v_regular_n;
  end if;

  if v_adj is not null then
    insert into public.walletfinal_all (master, transaction_number, date, event_type, event, appeal_id, payment_type, amount,
                                        receipt_photo, status, time, slice_date, slice_number, created_at, updated_at)
    values (p_master, public.wallet_new_transaction_number(), v_date, 'Выравнивание баланса', v_adj_event, null, v_adj_payment,
            v_adj_amount, null, 'подтверждено', v_time, v_date, v_slice, clock_timestamp(), clock_timestamp())
    returning to_jsonb(walletfinal_all.*) into v_adj_row;
  end if;

  if v_bal_amount is not null then
    insert into public.walletfinal_all (master, transaction_number, date, event_type, event, appeal_id, payment_type, amount,
                                        receipt_photo, status, time, slice_date, slice_number, created_at, updated_at)
    values (p_master, public.wallet_new_transaction_number(), v_date, 'Выравнивание баланса', 'Балансировка среза ' || v_slice,
            null, 'Системная операция', v_bal_amount, null, 'подтверждено', v_time, v_date, v_slice, clock_timestamp(), clock_timestamp())
    returning to_jsonb(walletfinal_all.*) into v_bal_row;
  end if;

  -- Из кошелька: строки к срезу и все старые долги
  delete from public.wallet_all w
   where w.master = p_master and w.slice_status = 'to_slice' and w.event_type <> all (c_debt_types);
  get diagnostics v_rows = row_count;
  if v_rows <> v_regular_n then
    raise exception 'Срез: из кошелька убрано % строк, ожидали %', v_rows, v_regular_n;
  end if;
  delete from public.wallet_all w where w.master = p_master and w.event_type = any (c_debt_types);
  get diagnostics v_rows = row_count;
  if v_rows <> v_debts_n then
    raise exception 'Срез: старых долгов убрано %, ожидали %', v_rows, v_debts_n;
  end if;

  -- «Учесть в долг»: один долг на весь прежний баланс
  if v_debt is not null then
    insert into public.wallet_all (master, transaction_number, date, time, event_type, event, appeal_id, payment_type, amount,
                                   receipt_photo, status, slice_status)
    values (p_master, public.wallet_new_transaction_number(), v_date, v_time,
            case when v_initial > 0 then 'ДОЛЖЕН МАСТЕР' else 'ДОЛЖНА КОМПАНИЯ' end,
            v_debt_comment || ' ' || v_slice, null, 'Отложенная выплата', abs(v_initial), null, 'неподтверждено', 'to_slice')
    returning to_jsonb(wallet_all.*) into v_new_debt;
  end if;

  insert into public.wallet_slice_log (master, slice_number, slice_date, mode, balance_before, moved, adjustment,
                                       balancing_amount, removed_debts, new_debt, seen, created_by, created_by_name)
  values (p_master, v_slice, v_date, case when v_debt is not null then 'в долг' else 'выравнивание' end, v_initial, v_moved,
          v_adj_row, v_bal_amount, v_removed_debts, v_new_debt, p_seen, v_uid, v_name);

  return jsonb_build_object(
    'ok', true,
    'slice_number', v_slice,
    'slice_date', v_date,
    'moved', v_regular_n,
    'balance_before', v_initial,
    'adjustment', v_adj_row,
    'balancing_amount', v_bal_amount,
    'removed_debts', v_debts_n,
    'new_debt', v_new_debt
  );
end;
$function$;

revoke all on function public.form_wallet_slice(text, jsonb, jsonb, jsonb) from public, anon;
grant execute on function public.form_wallet_slice(text, jsonb, jsonb, jsonb) to authenticated, service_role;
revoke all on function public.wallet_new_transaction_number() from public, anon;
grant execute on function public.wallet_new_transaction_number() to authenticated, service_role;
revoke all on function public.wallet_balance_part(text, text, numeric, text) from public, anon;
grant execute on function public.wallet_balance_part(text, text, numeric, text) to authenticated, service_role;

commit;

notify pgrst, 'reload schema';
