-- ============================================================================
-- Общая таблица топлива toplivo_all (разбор CRM/28 «Новый мастер», пункт 6).
--
-- Было: у каждого мастера своя таблица toplivo_<ключ> — 12 таблиц с одинаковыми колонками;
-- новому мастеру пришлось бы заводить ещё одну.
-- Стало: все поездки в одной таблице с колонкой master (ключ из public.masters).
-- Прежние имена toplivo_<ключ> остаются — представлениями в общую таблицу: CRM, сервер
-- и отмена договора (cancel_contract) читают и пишут как раньше, правок кода не нужно.
--
-- Устройство:
--   * ключ строки — (master, id): номера поездок у разных мастеров повторяются
--     (на 04.11 — 2 007 номеров у нескольких мастеров), старые номера сохраняем;
--   * новые номера — одна общая последовательность, выше всех прежних;
--   * представление: та же колонка за колонкой, что у таблицы, плюс master последней;
--     master по умолчанию — свой ключ, WITH CHECK OPTION не пустит чужого мастера;
--     security_invoker — права и RLS проверяются у того, кто зовёт;
--   * старые таблицы переименованы в toplivo_<ключ>_old и закрыты от API, не удалены;
--   * триггер updated_at — на общей таблице, теперь у всех мастеров
--     (раньше не было у daniil, dima, yglov).
-- Откат — PLANS/CRM/28-novyj-master/_syroe/toplivo-otkat.sql (переносит назад и новые строки).
-- ============================================================================

begin;

-- Чужая долгая транзакция на топливе — не ждать и не держать очередь запросов, а отказаться и повторить позже
set local lock_timeout = '5s';

-- Пока идёт перенос, никто не пишет в топливо
lock table public.toplivo_aleksei, public.toplivo_anton, public.toplivo_daniil, public.toplivo_dima,
  public.toplivo_evgeniy, public.toplivo_lesha, public.toplivo_roma, public.toplivo_semen,
  public.toplivo_timur, public.toplivo_vladimir, public.toplivo_vyacheslav, public.toplivo_yglov
  in access exclusive mode;

create table public.toplivo_all (
  master      text         not null references public.masters(key) on update restrict on delete restrict,
  id          integer      not null generated by default as identity,
  date        date         not null,
  time        time without time zone,
  address     varchar(255),
  place_id    varchar(255),
  appeal_id   varchar(255),
  contract_id varchar(255),
  event_type  varchar(100) not null,
  status      varchar(100) not null default 'не выплачено',
  comment     text,
  created_at  timestamptz  not null default now(),
  updated_at  timestamptz  not null default now(),
  primary key (master, id)
);

comment on table public.toplivo_all is
  'Топливо всех мастеров (с 04.11.2026). master — ключ из masters; номер поездки уникален внутри мастера. Читать и писать можно через toplivo_<ключ> — представления с master по умолчанию';

create index toplivo_all_appeal_id_idx on public.toplivo_all (appeal_id);
create index toplivo_all_contract_id_idx on public.toplivo_all (contract_id);
create index toplivo_all_master_date_idx on public.toplivo_all (master, date);

create trigger update_toplivo_all_updated_at
  before update on public.toplivo_all
  for each row execute function public.update_updated_at_column();

alter table public.toplivo_all enable row level security;
create policy "toplivo_all: менеджеры читают и пишут" on public.toplivo_all
  for all to authenticated using (true) with check (true);

revoke all on public.toplivo_all from public, anon;
grant select, insert, update, delete on public.toplivo_all to authenticated, service_role;

do $mig$
declare
  k text;
  n_old bigint;
  n_new bigint;
  v_max bigint;
  c_keys constant text[] := array['aleksei','anton','daniil','dima','evgeniy','lesha','roma','semen',
                                  'timur','vladimir','vyacheslav','yglov'];
begin
  foreach k in array c_keys loop
    if not exists (select 1 from public.masters where key = k) then
      raise exception 'Топливо: мастера % нет в masters', k;
    end if;

    execute format($q$
      insert into public.toplivo_all (master, id, date, time, address, place_id, appeal_id, contract_id,
                                      event_type, status, comment, created_at, updated_at)
      select %L, id, date, time, address, place_id, appeal_id, contract_id,
             event_type, status, comment, created_at, updated_at
      from public.%I$q$, k, 'toplivo_' || k);

    execute format('select count(*) from public.%I', 'toplivo_' || k) into n_old;
    select count(*) into n_new from public.toplivo_all where master = k;
    if n_old <> n_new then
      raise exception 'Топливо: у % было % поездок, перенеслось %', k, n_old, n_new;
    end if;

    execute format('alter table public.%I rename to %I', 'toplivo_' || k, 'toplivo_' || k || '_old');
    execute format('revoke all on public.%I from public, anon, authenticated, service_role', 'toplivo_' || k || '_old');
    execute format('comment on table public.%I is %L', 'toplivo_' || k || '_old',
      'Прежняя таблица топлива ' || k || ' до 04.11.2026; данные перенесены в toplivo_all. Не удалять до слова Яна');

    execute format($q$
      create view public.%I with (security_invoker = true) as
      select id, date, time, address, place_id, appeal_id, contract_id, event_type, status, comment,
             created_at, updated_at, master
      from public.toplivo_all
      where master = %L
      with local check option$q$, 'toplivo_' || k, k);
    execute format('alter view public.%I alter column master set default %L', 'toplivo_' || k, k);
    execute format('revoke all on public.%I from public, anon', 'toplivo_' || k);
    execute format('grant select, insert, update, delete on public.%I to authenticated, service_role', 'toplivo_' || k);
    execute format('comment on view public.%I is %L', 'toplivo_' || k,
      'Топливо мастера ' || k || ' — окно в toplivo_all (master = ' || k || ')');
  end loop;

  -- Новые номера — выше всех прежних, в том числе удалённых (последовательности старых таблиц)
  select greatest(
           coalesce((select max(id) from public.toplivo_all), 0),
           coalesce((select max(last_value) from pg_sequences
                     where schemaname = 'public' and sequencename like 'toplivo\_%'), 0))
    into v_max;
  perform setval(pg_get_serial_sequence('public.toplivo_all', 'id'), v_max, true);
end
$mig$;

commit;

notify pgrst, 'reload schema';
