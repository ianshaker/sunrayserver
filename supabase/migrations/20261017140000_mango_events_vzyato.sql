-- ============================================================================
-- Аренда события в журнале Mango (продолжение 20261017130000_mango_events.sql).
--
-- vzyato — когда Render взял событие в работу. Пока аренда моложе 60 с, повтор того же события получает
-- ответ «занято» (503) и прокси повторит позже; старше 60 с (прошлый заход упал или завис) — событие берут
-- заново. Новая строка получает vzyato сразу; у строк «только запись» (obrabotano = true) оно пустое.
--
-- Применять вместе с первым файлом, до выкладки сервера: без колонки журнал не пишется
-- (Render пишет ошибку в лог и обрабатывает звонок как раньше).
-- ============================================================================

alter table public.mango_events add column if not exists vzyato timestamptz;

comment on column public.mango_events.vzyato is
  'Когда Render взял событие в работу (аренда на 60 с); у событий, которые только записаны, пусто';
