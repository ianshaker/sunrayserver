-- ============================================================================
-- Общие таблицы кошельков и срезов: wallet_all и walletfinal_all (разбор CRM/28 «Новый мастер», пункт 6).
--
-- Было: у каждого мастера свой кошелёк wallet_<ключ> и свои срезы walletfinal_<ключ> — 24 таблицы;
-- новому мастеру пришлось бы заводить ещё две.
-- Стало: две общие таблицы с колонкой master (ключ из public.masters). Код CRM и функции базы
-- пишут прямо в них. Прежние имена на время переключения — окна в общие таблицы (как у топлива):
-- запись старой вкладки CRM не потеряется; окна и старые таблицы (_old) убираются на следующий день.
--
-- Устройство:
--   * ключ строки — (master, id): номера строк у разных мастеров повторяются (на 04.11 в срезах —
--     3 744 номера у нескольких мастеров, в кошельках — 2), старые номера сохраняем;
--   * новые номера — одна общая последовательность на таблицу, выше всех прежних;
--   * wallet_all: номер проводки transaction_number уникален по всем мастерам (между мастерами
--     повторов 0), CHECK статусов как у прежних таблиц;
--   * walletfinal_all: без UNIQUE на номер — в срезах 12 повторов внутри одного мастера, как было;
--   * finance_transactions_all (поиск, проверка свободного номера) — две ветки вместо 24, те же колонки;
--   * wallet_holds: вместо зашитого списка 12 мастеров — ссылка на masters.
-- Накатывается одним переключением вместе с 20261104150000 (топливо), 150100 (отмена договора)
-- и 150300 (apply_wallet_ops). Откат — PLANS/CRM/28-novyj-master/_syroe/wallet-otkat.sql.
-- ============================================================================

begin;

set local lock_timeout = '5s';

lock table
  public.wallet_aleksei, public.wallet_anton, public.wallet_daniil, public.wallet_dima, public.wallet_evgeniy,
  public.wallet_lesha, public.wallet_roma, public.wallet_semen, public.wallet_timur, public.wallet_vladimir,
  public.wallet_vyacheslav, public.wallet_yglov,
  public.walletfinal_aleksei, public.walletfinal_anton, public.walletfinal_daniil, public.walletfinal_dima,
  public.walletfinal_evgeniy, public.walletfinal_lesha, public.walletfinal_roma, public.walletfinal_semen,
  public.walletfinal_timur, public.walletfinal_vladimir, public.walletfinal_vyacheslav, public.walletfinal_yglov
  in access exclusive mode;

-- ---------- Кошельки ----------
create table public.wallet_all (
  master             text        not null references public.masters(key) on update restrict on delete restrict,
  id                 integer     not null generated by default as identity,
  transaction_number text        not null,
  date               date        not null,
  event_type         text        not null,
  event              text,
  appeal_id          text,
  payment_type       text        not null,
  amount             numeric     not null,
  receipt_photo      text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  status             text        not null default 'неподтверждено',
  time               time without time zone,
  slice_status       text        not null default 'unsorted',
  primary key (master, id),
  constraint wallet_all_transaction_number_key unique (transaction_number),
  constraint wallet_all_status_check check (status = any (array['подтверждено', 'неподтверждено'])),
  constraint wallet_all_slice_status_check check (slice_status = any (array['unsorted', 'to_slice', 'sliced']))
);
comment on table public.wallet_all is
  'Кошельки всех мастеров (с 04.11.2026). master — ключ из masters; номер строки уникален внутри мастера, номер проводки — по всем';
create index wallet_all_master_date_idx on public.wallet_all (master, date);
create index wallet_all_appeal_id_idx on public.wallet_all (appeal_id);

-- ---------- Срезы ----------
create table public.walletfinal_all (
  master             text        not null references public.masters(key) on update restrict on delete restrict,
  id                 integer     not null generated by default as identity,
  transaction_number text        not null,
  date               date        not null,
  event_type         text        not null,
  event              text,
  appeal_id          text,
  payment_type       text        not null,
  amount             numeric     not null,
  receipt_photo      text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  status             text        not null default 'неподтверждено',
  time               time without time zone,
  slice_date         date,
  slice_number       text,
  primary key (master, id)
);
comment on table public.walletfinal_all is
  'Срезы всех мастеров (с 04.11.2026). master — ключ из masters; номер строки уникален внутри мастера; номер проводки может повторяться (так было)';
create index walletfinal_all_master_event_type_idx on public.walletfinal_all (master, event_type);
create index walletfinal_all_master_slice_number_idx on public.walletfinal_all (master, slice_number);
create index walletfinal_all_transaction_number_idx on public.walletfinal_all (transaction_number);
create index walletfinal_all_appeal_id_idx on public.walletfinal_all (appeal_id);

create trigger update_wallet_all_updated_at
  before update on public.wallet_all for each row execute function public.update_updated_at_column();
create trigger update_walletfinal_all_updated_at
  before update on public.walletfinal_all for each row execute function public.update_updated_at_column();

alter table public.wallet_all enable row level security;
alter table public.walletfinal_all enable row level security;
create policy "wallet_all: менеджеры читают и пишут" on public.wallet_all
  for all to authenticated using (true) with check (true);
create policy "walletfinal_all: менеджеры читают и пишут" on public.walletfinal_all
  for all to authenticated using (true) with check (true);
revoke all on public.wallet_all, public.walletfinal_all from public, anon;
grant select, insert, update, delete on public.wallet_all, public.walletfinal_all to authenticated, service_role;

do $mig$
declare
  fam text;
  k text;
  cols text;
  n_old bigint;
  n_new bigint;
  s_old numeric;
  s_new numeric;
  v_max bigint;
  c_keys constant text[] := array['aleksei','anton','daniil','dima','evgeniy','lesha','roma','semen',
                                  'timur','vladimir','vyacheslav','yglov'];
begin
  foreach fam in array array['wallet', 'walletfinal'] loop
    cols := case fam
      when 'wallet' then 'id, transaction_number, date, event_type, event, appeal_id, payment_type, amount, receipt_photo, created_at, updated_at, status, time, slice_status'
      else               'id, transaction_number, date, event_type, event, appeal_id, payment_type, amount, receipt_photo, created_at, updated_at, status, time, slice_date, slice_number'
    end;

    foreach k in array c_keys loop
      if not exists (select 1 from public.masters where key = k) then
        raise exception 'Кошельки: мастера % нет в masters', k;
      end if;

      execute format('insert into public.%I (master, %s) select %L, %s from public.%I',
                     fam || '_all', cols, k, cols, fam || '_' || k);

      -- Сверка: строки и сумма до копейки
      execute format('select count(*), coalesce(sum(amount), 0) from public.%I', fam || '_' || k) into n_old, s_old;
      execute format('select count(*), coalesce(sum(amount), 0) from public.%I where master = $1', fam || '_all')
        into n_new, s_new using k;
      if n_old <> n_new or s_old <> s_new then
        raise exception '%: у % было % строк на %, перенеслось % на %', fam, k, n_old, s_old, n_new, s_new;
      end if;

      execute format('alter table public.%I rename to %I', fam || '_' || k, fam || '_' || k || '_old');
      execute format('revoke all on public.%I from public, anon, authenticated, service_role', fam || '_' || k || '_old');
      execute format('comment on table public.%I is %L', fam || '_' || k || '_old',
        'Прежняя таблица ' || fam || ' ' || k || ' до 04.11.2026; данные перенесены в ' || fam || '_all. Не удалять до слова Яна');

      -- Окно под прежним именем на время переключения: старый код пишет туда же
      execute format($q$
        create view public.%I with (security_invoker = true) as
        select %s, master from public.%I where master = %L
        with local check option$q$, fam || '_' || k, cols, fam || '_all', k);
      execute format('alter view public.%I alter column master set default %L', fam || '_' || k, k);
      execute format('revoke all on public.%I from public, anon', fam || '_' || k);
      execute format('grant select, insert, update, delete on public.%I to authenticated, service_role', fam || '_' || k);
      execute format('comment on view public.%I is %L', fam || '_' || k,
        'Окно в ' || fam || '_all (master = ' || k || ') на время переключения; убрать вместе с _old');
    end loop;

    -- Новые номера — выше всех прежних, в том числе удалённых (последовательности старых таблиц)
    select greatest(
             coalesce((select max(last_value) from pg_sequences
                       where schemaname = 'public' and sequencename like fam || '\_%\_id\_seq'
                         and sequencename not like '%\_all\_id\_seq' and sequencename <> 'wallet_holds_id_seq'), 0),
             0)
      into v_max;
    execute format('select greatest($1, coalesce(max(id), 0)) from public.%I', fam || '_all') into v_max using v_max;
    perform setval(pg_get_serial_sequence('public.' || fam || '_all', 'id'), v_max, true);
  end loop;
end
$mig$;

-- ---------- Все проводки одним видом: две ветки вместо 24, те же 15 колонок ----------
create or replace view public.finance_transactions_all with (security_invoker = true) as
select w.master, 'active'::text as source, w.id, w.transaction_number, w.date, w."time", w.event_type, w.event,
       w.appeal_id, w.payment_type, w.amount, w.status, w.slice_status, null::text as slice_number, null::date as slice_date
from public.wallet_all w
union all
select f.master, 'final'::text as source, f.id, f.transaction_number, f.date, f."time", f.event_type, f.event,
       f.appeal_id, f.payment_type, f.amount, f.status, null::text as slice_status, f.slice_number, f.slice_date
from public.walletfinal_all f;

-- ---------- Метки среза: мастер — из справочника, а не из зашитого списка ----------
alter table public.wallet_holds drop constraint wallet_holds_master_check;
alter table public.wallet_holds
  add constraint wallet_holds_master_fkey foreign key (master) references public.masters(key) on update restrict on delete restrict;

commit;

notify pgrst, 'reload schema';
